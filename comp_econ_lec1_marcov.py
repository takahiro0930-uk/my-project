"""NumPy adds displacement vectors entry by entry. A **dictionary** maps names to values: `moves["up"]` gives the upward displacement.

A **policy** maps a state to an action. `if` / `else` chooses between cases. This policy goes up, then right, avoiding the wall from our start.
"""

def up_then_right(state):
    if state[0] > 0:
        return "up"
    else:
        return "right"

print("Action at the start:", up_then_right(np.array([2, 0])))
print("Action at the top-left corner:", up_then_right(np.array([0, 0])))

"""## 10. Build the maze object

`step(state, action)` returns the next state and reward. `simulate(policy, ...)` calls the policy and applies `step` repeatedly.

- `{...}` defines a dictionary; `np.array_equal` compares arrays.
- `and` requires both conditions; `not` reverses a Boolean.
- `state, reward = ...` **unpacks** two results; `.copy()` keeps a separate array.

Here each state/action pair determines one next cell. MDP transitions can also be random.
"""

class MazeMDP:
    def __init__(self):
        self.goal = np.array([0, 2])
        self.wall = np.array([1, 1])
        self.beta = 0.95
        self.moves = {
            "up": np.array([-1, 0]),
            "down": np.array([1, 0]),
            "left": np.array([0, -1]),
            "right": np.array([0, 1])
        }

    def step(self, state, action):
        if np.array_equal(state, self.goal):
            return state.copy(), 0
        next_state = state + self.moves[action]
        inside = np.all(next_state >= 0) and np.all(next_state < 3)
        if not inside or np.array_equal(next_state, self.wall):
            next_state = state.copy()
        return next_state, -1

    def simulate(self, policy, initial_state, periods):
        state = np.array(initial_state)
        path = [state.copy()]
        rewards = []
        for period in range(periods):
            action = policy(state)
            state, reward = self.step(state, action)
            path.append(state.copy())
            rewards.append(reward)
        return np.array(path), np.array(rewards)

"""`self.beta` stores the discount factor $\beta=0.95$ for later lectures. Pass `up_then_right` **without parentheses** so `simulate` can call the function at each state."""

maze = MazeMDP()
maze_path, rewards = maze.simulate(up_then_right, initial_state=[2, 0], periods=6)
print("Locations, including the start:")
print(maze_path)
print("Rewards for the six moves:", rewards)

